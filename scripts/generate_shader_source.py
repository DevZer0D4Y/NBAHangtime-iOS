#!/usr/bin/env python3
"""Generate both CRT backends from one shared math source."""
from pathlib import Path
import argparse
import json
import re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true', help='Reject stale generated shaders')
args = parser.parse_args()
math = (root / 'shared/newpixie.glsl').read_text()
gl = '''#version 120
uniform sampler2D sourceTex,feedbackTex,blurTex;
uniform vec2 sourceSize,outputSize;
uniform float frame;
uniform int mode;
varying vec2 uv;
''' + math + '''
void main() {
 if(mode==1) gl_FragColor=max(texture2D(feedbackTex,uv)*0.65,texture2D(sourceTex,uv)*0.96);
 else if(mode==2) gl_FragColor=blur9(sourceTex,uv,vec2(1.0/sourceSize.x,0));
 else if(mode==3) gl_FragColor=blur9(sourceTex,uv,vec2(0,1.0/sourceSize.y));
 else if(mode==4) gl_FragColor=newpixie(sourceTex,blurTex,uv,outputSize,frame);
 else gl_FragColor=texture2D(sourceTex,uv);
}
'''
metal_math = re.sub(r'\bvec([234])\b', r'float\1', math).replace('sampler2D', 'texture2d<float>')
metal_math = metal_math.replace('texture2D(', 'sampleTex(').replace('mod(', 'fmod(')
metal = '''#include <metal_stdlib>
using namespace metal;
float4 sampleTex(texture2d<float> tex, float2 uv) {
 constexpr sampler s(coord::normalized, address::clamp_to_edge, filter::linear);
 return tex.sample(s,uv);
}
struct V { float4 position [[position]]; float2 uv; };
vertex V crtVertex(uint id [[vertex_id]]) {
 float2 p=float2((id<<1)&2,id&2);
 V v;v.position=float4(p*float2(2,-2)+float2(-1,1),0,1);v.uv=p;return v;
}
struct Params { float2 sourceSize;float2 outputSize;float frame;int mode; };
''' + metal_math + '''
fragment float4 crtFragment(V v [[stage_in]], texture2d<float> src [[texture(0)]],
 texture2d<float> feedback [[texture(1)]],texture2d<float> blur [[texture(2)]],constant Params &p [[buffer(0)]]) {
 if(p.mode==1) return max(sampleTex(feedback,v.uv)*0.65,sampleTex(src,v.uv)*0.96);
 if(p.mode==2) return blur9(src,v.uv,float2(1.0/p.sourceSize.x,0));
 if(p.mode==3) return blur9(src,v.uv,float2(0,1.0/p.sourceSize.y));
 if(p.mode==4) return newpixie(src,blur,v.uv,p.outputSize,p.frame);
 if(p.mode==5) return sampleTex(src,v.uv);
 constexpr sampler nearestSampler(coord::normalized,address::clamp_to_edge,filter::nearest);
 return src.sample(nearestSampler,v.uv);
}
'''
vertex = '#version 120\nvarying vec2 uv;void main(){gl_Position=gl_Vertex;uv=gl_MultiTexCoord0.xy;}'
header = '/* Generated by scripts/generate_shader_source.py; see licenses/NewPixie-MIT.txt. */\n'
header += 'static const char *crt_fragment=\n' + '\n'.join(json.dumps(line) for line in gl.splitlines(keepends=True)) + ';\n'
header += 'static const char *crt_vertex=' + json.dumps(vertex) + ';\n'
swift = ('// Generated by scripts/generate_shader_source.py from shared/newpixie.glsl.\n'
         'enum NewPixieShader {\n    static let source = #"""\n' + metal + '\n"""#\n}\n')
for name, content in {'desktop/Shaders.h': header, 'ios/Hangtime/NewPixie.metal': metal,
                      'ios/Hangtime/ShaderSource.swift': swift}.items():
    path = root / name
    if args.check:
        if path.read_text() != content:
            raise SystemExit('Stale shader: ' + name + '; run scripts/generate_shader_source.py')
    else:
        path.write_text(content)
